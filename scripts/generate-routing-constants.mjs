#!/usr/bin/env node
/**
 * Generate the list of files served from `public/` at the site root.
 *
 * The proxy needs it. Until now the matcher excluded every path containing a
 * dot, which kept `/logo.svg` out of the proxy — and `/admin.php` with it. Once
 * the matcher stops doing that, the proxy sees static assets too and has to be
 * able to tell them apart from junk, so it needs the actual list.
 *
 * Deliberately committed and NOT regenerated during `next build`. A build that
 * writes into the tree would dirty the working copy, and
 * `scripts/ops/deploy-production.sh` refuses to deploy a dirty tree. The drift
 * test in `src/lib/routing-generated.test.ts` is what keeps it honest instead: add a
 * file to `public/` without re-running this and the test fails.
 *
 *   pnpm generate:routing
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, posix, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const publicDir = join(root, "public");
const outFile = join(root, "src", "lib", "routing.generated.ts");

/** Every file under `public/`, as the root-relative URL path it is served at. */
export function collectPublicAssets(dir = publicDir) {
	const out = [];
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) {
			out.push(...collectPublicAssets(full));
			continue;
		}
		out.push("/" + relative(publicDir, full).split(sep).join(posix.sep));
	}
	return out.sort();
}

/**
 * Next's own root metadata routes, derived from the files that produce them
 * rather than from a list somebody has to remember to update.
 *
 * `robots.ts` -> /robots.txt, `sitemap.ts` -> /sitemap.xml, and the image
 * conventions serve at their own filename. They are not in `public/`, but from
 * the proxy's point of view they are the same thing: root paths with a dot that
 * must not be mistaken for a market.
 */
const METADATA_CONVENTIONS = {
	"robots.ts": "/robots.txt",
	"robots.js": "/robots.txt",
	"sitemap.ts": "/sitemap.xml",
	"sitemap.js": "/sitemap.xml",
	"manifest.ts": "/manifest.webmanifest",
	"manifest.js": "/manifest.webmanifest",
	"favicon.ico": "/favicon.ico",
	"icon.png": "/icon.png",
	"icon.svg": "/icon.svg",
	"apple-icon.png": "/apple-icon.png",
	"opengraph-image.png": "/opengraph-image.png",
	"opengraph-image.tsx": "/opengraph-image.png",
	"twitter-image.png": "/twitter-image.png",
	"twitter-image.tsx": "/twitter-image.png",
};

/**
 * Path segments that sit directly under the market prefix and are REAL routes.
 *
 * `[productSlug]` is a catch-all at the market root, so every one of these looks
 * like a product slug from the outside. A route-existence gate that asks Saleor
 * about "poradna", gets null and 404s would take a live legal page off the site —
 * `/sk/odstupenie-od-zmluvy` is in the sitemap and has statutory consequences.
 *
 * Derived from the filesystem so it cannot drift. Route groups like `(main)` are
 * transparent and dynamic segments are excluded: a `[slug]` directory IS the
 * catch-all, not a static sibling.
 */
export function collectMarketRootSegments(mainDir = join(root, "src", "app", "[channel]")) {
	const out = new Set();

	const walk = (dir) => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			if (!entry.isDirectory()) continue;
			// Route groups are transparent: (main)/kontakt serves at /{market}/kontakt.
			if (entry.name.startsWith("(") && entry.name.endsWith(")")) {
				walk(join(dir, entry.name));
				continue;
			}
			// Private folders are not routed at all.
			if (entry.name.startsWith("_")) continue;
			// A dynamic segment is the catch-all itself, not a static sibling.
			if (entry.name.startsWith("[")) continue;
			out.add(entry.name);
		}
	};

	walk(mainDir);
	return [...out].sort();
}

export function collectMetadataRoutes(appDir = join(root, "src", "app")) {
	const out = new Set();
	for (const entry of readdirSync(appDir)) {
		const served = METADATA_CONVENTIONS[entry];
		if (served) out.add(served);
	}
	return [...out].sort();
}

export function renderModule(
	assets = collectPublicAssets(),
	metadataRoutes = collectMetadataRoutes(),
	marketRootSegments = collectMarketRootSegments(),
) {
	return `// GENERATED by scripts/generate-routing-constants.mjs — do not edit by hand.
// Run \`pnpm generate:routing\` after adding or removing a file in public/
// or a root metadata convention in src/app/.
// src/lib/routing-generated.test.ts fails if this drifts.

/**
 * Root paths the proxy must pass straight through.
 *
 * Until 2026-08-06 the matcher excluded every path containing a dot, which kept
 * \`/logo.svg\` out of the proxy — and \`/admin.php\` with it, so junk URLs
 * bypassed the invalid-first-segment gate and answered 200 + index,follow with a
 * self-canonical. Now the matcher lets dotted paths in, and this is how the real
 * assets are told apart from the junk: \`/logo.svg\` looks exactly like a bogus
 * market prefix from the outside.
 */
export const PUBLIC_ASSET_PATHS: ReadonlySet<string> = new Set([
${assets.map((a) => `\t${JSON.stringify(a)},`).join("\n")}
]);

/** Next's own root metadata routes (robots.ts -> /robots.txt, and friends). */
export const METADATA_ROUTE_PATHS: ReadonlySet<string> = new Set([
${metadataRoutes.map((a) => `\t${JSON.stringify(a)},`).join("\n")}
]);

/**
 * Real static routes directly under the market prefix.
 *
 * \`[productSlug]\` is a catch-all at that level, so each of these is
 * indistinguishable from a product slug by shape. Anything asking "is this a
 * product?" has to consult this list first — see \`src/lib/route-policy.ts\`.
 */
export const MARKET_ROOT_SEGMENTS: ReadonlySet<string> = new Set([
${marketRootSegments.map((a) => `\t${JSON.stringify(a)},`).join("\n")}
]);
`;
}

// Only write when run as a script. The drift test imports the collectors, and an
// import that rewrites a source file would make the test pass by fixing what it
// was meant to catch.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const assets = collectPublicAssets();
	const metadataRoutes = collectMetadataRoutes();
	const marketRootSegments = collectMarketRootSegments();
	writeFileSync(outFile, renderModule(assets, metadataRoutes, marketRootSegments));
	console.log(
		`generate:routing — wrote ${assets.length} public paths, ${metadataRoutes.length} metadata ` +
			`routes and ${marketRootSegments.length} market-root segments to ${relative(root, outFile)}`,
	);
}
